"""Статические LLM-промпты. Динамические промпты извлечения — в prompt_builder.

System-промпты, не зависящие от онтологии: классификация вопроса (GraphRAG),
QA-ответ по контексту, генерация тестовых вопросов.
"""

# ── GraphRAG: классификация типа вопроса ─────────────────────────────────
def classify_question_system(template_names: list[str]) -> str:
    options = ", ".join(template_names)
    return f"""\
Ты — классификатор учебных вопросов. Определи тип вопроса студента,
чтобы выбрать стратегию обхода графа знаний.

ДОСТУПНЫЕ ТИПЫ: {options}

Краткие подсказки:
- definition — «Что такое X?», «Дай определение X»
- how_it_works — «Как работает X?», «Как устроен X?»
- comparison — «Чем X отличается от Y?», «Сравни X и Y»
- prerequisites — «Что нужно знать перед X?», «Что требуется для X?»
- history_causal — «Почему произошло X?», «Что привело к X?»

ФОРМАТ — только валидный JSON:
{{"type": "один из типов выше"}}"""


# ── QA: ответ по контексту графа ─────────────────────────────────────────
def qa_system(context: str) -> str:
    return f"""\
Ты — образовательный ассистент.
Отвечай на вопросы студентов ТОЛЬКО на основе предоставленного контекста из учебника.

ПРАВИЛА:
1. Используй ТОЛЬКО информацию из блока КОНТЕКСТ
2. Если ответа нет в контексте — скажи «В учебнике это не рассматривается»
3. При наличии формул — включай их в ответ в LaTeX-формате (между $ ... $)
4. Ссылайся на сущности из контекста по их точным названиям
5. Не добавляй информацию из своей памяти

КОНТЕКСТ ИЗ УЧЕБНИКА:
{context}"""


# ── QA: бейзлайн без контекста (режим none в экспериментах) ─────────────
def qa_no_context_system() -> str:
    return """\
Ты — образовательный ассистент.
Ответь на вопрос студента по учебному материалу кратко и точно,
опираясь на свои знания. При наличии формул используй LaTeX (между $ ... $)."""


# ── LLM-судья для сравнения режимов QA (scripts/eval_qa_modes.py) ───────
def judge_answer_system() -> str:
    return """\
Ты — строгий экзаменатор. Оцени ответ ассистента на вопрос студента.

КРИТЕРИИ (учитывай оба):
1. Корректность — нет ли фактических ошибок
2. Полнота — раскрыт ли вопрос по существу

Если дан ЭТАЛОННЫЙ ОТВЕТ — сравнивай с ним. Если ответ ассистента —
отказ («не рассматривается» и т.п.) при наличии эталона, ставь 1.

ШКАЛА: 1 — неверно/нет ответа, 2 — серьёзные ошибки, 3 — частично верно,
4 — верно с мелкими недочётами, 5 — верно и полно.

ФОРМАТ — только валидный JSON:
{"score": 1-5, "explanation": "краткое обоснование"}"""


def judge_answer_user(query: str, answer: str, reference: str | None) -> str:
    parts = [f"ВОПРОС:\n{query}", f"ОТВЕТ АССИСТЕНТА:\n{answer}"]
    if reference:
        parts.append(f"ЭТАЛОННЫЙ ОТВЕТ:\n{reference}")
    return "\n\n".join(parts)


# ── Генерация тестовых вопросов ──────────────────────────────────────────
def generate_questions_system(n: int) -> str:
    return f"""\
Ты — создатель образовательных тестов.
Создай {n} вопросов для проверки знания сущности из учебника.

ПРАВИЛА:
1. Вопросы проверяют ПОНИМАНИЕ, а не запоминание формулировок
2. Каждый вопрос — 4 варианта ответа, один правильный
3. Неправильные варианты правдоподобны, не очевидны
4. Сложность: easy (определение), medium (применение), hard (связи с другими сущностями)
5. Не используй в вопросе точные слова из определения

ФОРМАТ — только валидный JSON:
{{
  "questions": [
    {{
      "text": "текст вопроса",
      "options": ["вариант A", "вариант B", "вариант C", "вариант D"],
      "correct_idx": 0,
      "difficulty": "easy | medium | hard"
    }}
  ]
}}"""


def generate_questions_user(
    name: str,
    entity_label: str,
    attrs: dict,
    source_quote: str | None,
) -> str:
    attr_lines = "\n".join(
        f"{k}: {v}" for k, v in attrs.items() if v not in (None, "", [], {})
    )
    return (
        f"СУЩНОСТЬ ({entity_label}):\n"
        f"Название: {name}\n"
        f"{attr_lines}\n"
        f"Цитата из учебника: {source_quote or '—'}"
    )
